/// Every word the guard and CSO screens show or say, keyed by message id, in one place.
///
/// English only today. Yoruba and Pidgin are added as more tables in [_tables] (a missing
/// line falls back to English), and [lang] picks one. Placeholders are `{name}`.
///
/// Rules for every line: plain short English, no em dashes, no paragraphs. Never put a PIN, a
/// phone number, a code or a card id in a spoken line.
library;

import 'kit.dart' show speak;

enum Lang { en }

Lang lang = Lang.en;

const Map<Lang, Map<M, String>> _tables = {Lang.en: {}};

/// The line for [m] in the current language, with `{placeholders}` filled from [args].
String tr(M m, [Map<String, Object?> args = const {}]) {
  var s = _tables[lang]?[m] ?? m.en;
  for (final e in args.entries) {
    s = s.replaceAll('{${e.key}}', '${e.value ?? ''}');
  }
  return s;
}

/// Reads [m] aloud.
Future<void> say(M m, [Map<String, Object?> args = const {}]) => speak(tr(m, args));

